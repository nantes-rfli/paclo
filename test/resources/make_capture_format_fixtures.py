"""Deterministic synthetic P08-A fixtures; no capture privileges or dependencies.

Run from any directory: python3 test/resources/make_capture_format_fixtures.py
Use --check to compare generated bytes/manifest with the checked-in artifacts.
See dev/p08-a-capture-formats.md for format sources, reuse and expectations.
"""
import argparse
import json
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / 'capture-formats'
IP = bytes.fromhex('4500003200010000401100000a0000010a000002')
UDP = struct.pack('>HHHH', 12000, 53, 30, 0) + bytes(22)
ETH = bytes(range(12)) + bytes.fromhex('0800') + IP + UDP
SLL = struct.pack('>HHH8sH', 0, 1, 6, bytes(range(6)) + bytes(2), 0x0800)
SLL2 = struct.pack('>HHIHBB8s', 0x0800, 0, 7, 1, 0, 6, bytes(range(6)) + bytes(2))
SEC = 1700000000
artifacts = {}
cases = []


def pad(data):
    return data + bytes((-len(data)) % 4)


def block(kind, body, endian='<'):
    body = pad(body)
    length = len(body) + 12
    return struct.pack(endian + 'II', kind, length) + body + struct.pack(endian + 'I', length)


def options(items, endian='<'):
    return b''.join(struct.pack(endian + 'HH', code, len(value)) + pad(value)
                    for code, value in items) + bytes(4)


def shb(endian='<'):
    return block(0x0a0d0d0a, struct.pack(endian + 'IHHq', 0x1a2b3c4d, 1, 0, -1)
                 + options([(1, b'synthetic section')], endian), endian)


def idb(link=1, resolution=None, offset=None, snaplen=65536, endian='<'):
    items = [(1, b'interface comment'), (2, b'synthetic0'), (0x8001, b'unknown option')]
    if resolution is not None:
        items.append((9, bytes([resolution])))
    if offset is not None:
        items.append((14, struct.pack(endian + 'q', offset)))
    return block(1, struct.pack(endian + 'HHI', link, 0, snaplen)
                 + options(items, endian), endian)


def epb(interface=0, ticks=SEC * 1000000 + 123456, data=ETH, length=None, endian='<'):
    return block(6, struct.pack(endian + 'IIIII', interface, ticks >> 32,
                               ticks & 0xffffffff, len(data), len(data) if length is None else length)
                 + pad(data) + options([(1, b'packet comment'), (0x8001, b'unknown packet option')], endian), endian)


def record(data=ETH, sec=SEC, fraction=123456, length=None):
    return {'hex': data.hex(), 'ts-sec': sec, 'ts-usec': fraction,
            'caplen': len(data), 'len': len(data) if length is None else length}


def add(name, content, records, link=1, terminal='eof', error=None):
    artifacts[name] = content
    cases.append({'file': name, 'linktype': link, 'records': records,
                  'terminal': terminal, 'error-pattern': error})


def classic(link, data, nano=False, endian='<'):
    magic = 0xa1b23c4d if nano else 0xa1b2c3d4
    fraction = 123456789 if nano else 123456
    return struct.pack(endian + 'IHHIIII', magic, 2, 4, 0, 0, 65536, link) + struct.pack(
        endian + 'IIII', SEC, fraction, len(data), len(data)) + data


for name, link, data in [('ethernet', 1, ETH), ('sll2', 276, SLL2 + IP + UDP),
                         ('raw', 101, IP + UDP), ('loop', 108, struct.pack('>I', 2) + IP + UDP)]:
    add(name + '.pcap', classic(link, data), [record(data)], link='raw' if link == 101 else link)
add('ethernet-nano.pcap', classic(1, ETH, nano=True), [record()])
add('ethernet-big-endian.pcap', classic(1, ETH, endian='>'), [record()])
base = shb() + idb()
add('single.pcapng', base + epb(), [record()])
add('big-endian.pcapng', shb('>') + idb(endian='>') + epb(endian='>'), [record()])
add('multi-interface.pcapng', base + epb() + idb() + epb(1), [record(), record()])
add('multi-linktype.pcapng', base + epb() + idb(113) + epb(1, data=SLL + IP + UDP), [record()],
    terminal='error', error='different.*type|type.*different')
add('multi-snaplen.pcapng', base + epb() + idb(snaplen=9000) + epb(1), [record()],
    terminal='error', error='snapshot length|snaplen')
add('nano.pcapng', shb() + idb(resolution=9) + epb(ticks=SEC * 10**9 + 123456789), [record()])
add('mixed-resolution.pcapng', base + epb() + idb(resolution=9)
    + epb(1, SEC * 10**9 + 123456789), [record(), record()])
add('binary-resolution.pcapng', shb() + idb(resolution=0x8a)
    + epb(ticks=SEC * 1024 + 129), [record(fraction=125976)])
add('offset.pcapng', shb() + idb(offset=7) + epb(), [record(sec=SEC + 7)])
add('multi-section.pcapng', base + epb() + base + epb(), [record(), record()])
add('mixed-endian-section.pcapng', base + epb() + shb('>') + idb(endian='>') + epb(endian='>'),
    [record()], terminal='error', error='byte order|endianness|block size')
add('unknown-block.pcapng', base + block(0x80000042, b'private data') + epb(), [record()])
add('truncated.pcapng', base + epb(data=ETH[:16], length=1500), [record(ETH[:16], length=1500)])
add('invalid-original-length.pcapng', base + epb(length=1), [record(length=1)])
add('simple-packet.pcapng', base + block(3, struct.pack('<I', len(ETH)) + ETH),
    [record(sec=0, fraction=0)])
add('bad-interface.pcapng', base + epb(interface=9), [], terminal='error', error='interface')
add('bad-caplen.pcapng', base + epb(data=bytes(65537)), [], terminal='error', error='capture length|snaplen')
add('short-block.pcapng', base + struct.pack('<II', 6, 8), [], terminal='error', error='block')
add('bad-trailer.pcapng', base + epb()[:-4] + struct.pack('<I', 12), [],
    terminal='error', error='block|length')
add('cut-block.pcapng', base + epb()[:-20], [], terminal='error', error='truncated|block')
add('bad-idb-option.pcapng', shb() + block(1, struct.pack('<HHI', 1, 0, 65536)
    + options([(9, bytes(2))])), [], terminal='open-error', error='if_tsresol')
add('bad-pcap-length.pcap', classic(1, ETH)[:24] + struct.pack('<IIII', SEC, 0, 65537, 65537),
    [], terminal='error', error='invalid.*length|truncated')
artifacts['manifest.json'] = (json.dumps(cases, indent=2) + '\n').encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    OUTPUT.mkdir(exist_ok=True)
    for name, content in artifacts.items():
        path = OUTPUT / name
        if args.check:
            if not path.exists() or path.read_bytes() != content:
                raise SystemExit('Fixture mismatch: ' + str(path))
        else:
            path.write_bytes(content)
    print(('Verified' if args.check else 'Generated') + f' {len(cases)} capture fixtures and manifest')
    from make_cooked_fixtures import generate
    generate(args.check)
    from make_raw_ip_fixtures import generate as generate_raw
    generate_raw(args.check)
    from make_null_loop_fixtures import generate as generate_null_loop
    generate_null_loop(args.check)


if __name__ == '__main__':
    main()
